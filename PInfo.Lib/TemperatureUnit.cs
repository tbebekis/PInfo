namespace PInfo;

/// <summary>
/// Specifies the display unit for weather temperatures; source data remains in Celsius.
/// </summary>
public enum TemperatureUnit
{
    /// <summary>
    /// Displays temperatures in degrees Celsius.
    /// </summary>
    Celsius = 0,
    /// <summary>
    /// Displays temperatures in degrees Fahrenheit.
    /// </summary>
    Fahrenheit = 1
}
